// NOTE: 初始化检测安卓系统主语言设置 (zh-CN 或 en-US)
const getSystemLanguage = (): string => {
  const savedLang = storage.getString(LANGUAGE_KEY);
  if (savedLang) return savedLang;

  const locales = Localization.getLocales();
  if (locales && locales.length > 0) {
    const localeCode = locales[0].languageTag;
    if (localeCode.startsWith('zh')) {
      return 'zh-CN';
    }
  }
  return 'en-US';
};

i18n
  .use(initReactI18next)
  .init({
    compatibilityJSON: 'v4', // 兼容 React Native 环境
    resources: {
      'zh-CN': { translation: translations['zh-CN'] },
      'en-US': { translation: translations['en-US'] }
    },
    lng: getSystemLanguage(),
    fallbackLng: 'en-US',
    interpolation: {
      escapeValue: false // react already safes from xss
    }
  });

// NOTE: 提供外部手动切换语言方法并持久化至 MMKV 快速存储
export const changeLanguage = async (lang: 'zh-CN' | 'en-US') => {
  storage.set(LANGUAGE_KEY, lang);
  await i18n.changeLanguage(lang);
};

export default i18n;
